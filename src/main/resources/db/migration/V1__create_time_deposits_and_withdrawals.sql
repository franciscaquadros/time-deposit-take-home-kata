CREATE TABLE time_deposits (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_type VARCHAR(255) NOT NULL,
    days INTEGER NOT NULL,
    balance NUMERIC(19, 2) NOT NULL
);

CREATE TABLE withdrawals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_deposit_id INTEGER NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    date DATE NOT NULL,
    CONSTRAINT fk_withdrawal_deposit FOREIGN KEY (time_deposit_id) REFERENCES time_deposits (id)
);

CREATE INDEX idx_withdrawals_deposit ON withdrawals (time_deposit_id);
